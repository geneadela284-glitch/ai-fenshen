const TERMINAL_PLAYBACK_ACTION_CODES = new Set([
  'PLAYBACK_BINDING_MISMATCH',
  'PLAYBACK_SOURCE_BOUNDARY_UNVERIFIED',
  'PLAYBACK_UNSUPPORTED',
  'PLAYBACK_MIME_UNSUPPORTED',
  'PLAYBACK_INDEPENDENT_SOURCE_UNSUPPORTED',
  'PLAYBACK_AAC_SOURCE_UNSUPPORTED',
  'PLAYBACK_CONTAINER_LAYOUT_UNSUPPORTED',
  'PLAYBACK_INIT_SEGMENT_UNAVAILABLE',
  'PLAYBACK_MANAGER_DISPOSED',
  'PLAYBACK_NOT_OPEN',
  'PLAYBACK_DEPENDENCY_UNAVAILABLE',
  'PLAYBACK_PLAYER_UNAVAILABLE',
  'PLAYBACK_AUDIO_ELEMENT_UNAVAILABLE',
  'PLAYBACK_OBJECT_URL_FAILED',
  'PLAYBACK_BYTES_INVALID',
  'PLAYBACK_SOURCE_TIMELINE_EMPTY',
  'PLAYBACK_SOURCE_TIMELINE_INVALID',
  'PLAYBACK_SOURCE_TIMELINE_MISMATCH',
  'PLAYBACK_WINDOW_LIMIT_INVALID',
  'PLAYBACK_SEEK_TARGET_INVALID'
]);

export function isTerminalPlaybackActionError(error) {
  const code = String(error?.code || error?.message || '').trim();
  return TERMINAL_PLAYBACK_ACTION_CODES.has(code);
}
