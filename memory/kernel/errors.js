export const MEMORY_KERNEL_ERROR_CODES = Object.freeze([
  'INVALID_TYPE',
  'REQUIRED',
  'UNKNOWN_FIELD',
  'UNSUPPORTED_SCHEMA_VERSION',
  'INVALID_ENUM',
  'INVALID_NUMBER',
  'INVALID_DATE',
  'INVALID_RANGE',
  'USER_SCOPE_REQUIRED',
  'USER_SCOPE_MISMATCH',
  'SOURCE_REQUIRED',
  'MODEL_CONFIRMED_FORBIDDEN',
  'CANDIDATE_STATUS_REQUIRED',
  'CONFIRMATION_REQUIRED',
  'SECRET_FORBIDDEN',
  'INVALID_TRANSITION',
  'INTERFACE_METHOD_MISSING',
  'INVARIANT_VIOLATION',
  'MEMORY_EXPECTED_VERSION_REQUIRED',
  'MEMORY_VERSION_CONFLICT',
  'MEMORY_RECORD_NOT_FOUND',
  'MEMORY_TRANSACTION_FAILED',
  'MEMORY_NESTED_TRANSACTION_UNSUPPORTED',
  'MEMORY_BATCH_ATOMICITY_FAILED',
  'MEMORY_IDEMPOTENCY_CONFLICT'
]);

export function createMemoryKernelError(path, code, message) {
  const normalizedCode = MEMORY_KERNEL_ERROR_CODES.includes(code) ? code : 'INVARIANT_VIOLATION';
  return Object.freeze({
    path: String(path || ''),
    code: normalizedCode,
    message: String(message || normalizedCode)
  });
}
